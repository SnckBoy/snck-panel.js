#!/usr/bin/env bash
set -Eeuo pipefail

# ============================================================================
#  SNCK Panel — Node.js edition installer
#
#  One command:
#    curl -fsSL https://raw.githubusercontent.com/SnckBoy/snck-panel.js/main/install.sh | sudo bash
#
#  Non-interactive:
#    curl -fsSL .../install.sh | sudo SNCK_NONINTERACTIVE=1 bash
#
#  This installs the Node.js/Express panel only. Minecraft servers are run by
#  Docker on the selected panel host or on a connected VPS node.
# ============================================================================

REPO_URL="${SNCK_REPO_URL:-https://github.com/SnckBoy/snck-panel.js.git}"
BRANCH="${SNCK_BRANCH:-main}"
APP_DIR="${SNCK_PANEL_DIR:-/opt/snck-panel}"
SERVICE="snck-panel"
SERVICE_USER="${SNCK_SERVICE_USER:-snck}"
SERVICE_HOME="${SNCK_SERVICE_HOME:-/var/lib/snck}"
PORT="${SNCK_PORT:-6767}"
SFTP_PORT="${SNCK_SFTP_PORT:-6868}"
NODE_MAJOR=22

if [[ -t 1 ]]; then
  B=$'\033[1m'; DIM=$'\033[2m'; RED=$'\033[31m'; GREEN=$'\033[32m'
  YELLOW=$'\033[33m'; CYAN=$'\033[36m'; R=$'\033[0m'
else
  B=""; DIM=""; RED=""; GREEN=""; YELLOW=""; CYAN=""; R=""
fi

info() { printf '%s[INFO]%s %s\n' "$CYAN" "$R" "$*"; }
ok()   { printf '%s[ OK ]%s %s\n' "$GREEN" "$R" "$*"; }
warn() { printf '%s[WARN]%s %s\n' "$YELLOW" "$R" "$*"; }
die()  { printf '%s[FAIL]%s %s\n' "$RED" "$R" "$*" >&2; exit 1; }

TTY_FD=3
TTY_OK=0
if { : >/dev/tty; } 2>/dev/null; then exec 3</dev/tty; TTY_OK=1; else exec 3</dev/null; fi
ask() { local prompt="$1" default="${2:-}" answer=""; printf '%s' "$prompt" >&2; IFS= read -r -u 3 answer || true; printf '%s' "${answer:-$default}"; }
pause() { printf '\n%sPress Enter to continue…%s' "$DIM" "$R" >&2; IFS= read -r -u 3 _ || true; }

require_root() { [[ ${EUID} -eq 0 ]] || die "Run this installer as root (use sudo)."; }
has_systemd() { command -v systemctl >/dev/null 2>&1 && [[ -d /run/systemd/system ]]; }

check_os() {
  [[ -r /etc/os-release ]] || die "Cannot detect this operating system."
  # shellcheck disable=SC1091
  . /etc/os-release
  case "${ID:-}" in
    ubuntu|debian) ;;
    *) warn "Tested on Ubuntu/Debian. Continuing on ${PRETTY_NAME:-$ID} at your own risk." ;;
  esac
}

install_packages() {
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -y
  apt-get install -y ca-certificates curl git openssl xz-utils build-essential
}

install_node() {
  if command -v node >/dev/null 2>&1; then
    local current
    current="$(node -p 'process.versions.node.split(".")[0]' 2>/dev/null || echo 0)"
    if [[ "$current" -ge 20 ]]; then
      ok "Node.js $(node -v) is already available."
      return
    fi
  fi
  info "Installing Node.js ${NODE_MAJOR}.x…"
  if ! (curl -fsSL "https://deb.nodesource.com/setup_${NODE_MAJOR}.x" | bash - && apt-get install -y nodejs); then
    warn "NodeSource is unavailable; using the official Node.js binary."
    local arch
    case "$(dpkg --print-architecture)" in
      amd64) arch=x64 ;;
      arm64) arch=arm64 ;;
      *) die "No official Node.js binary for $(dpkg --print-architecture)." ;;
    esac
    local version="22.14.0" root="/opt/nodejs/node-v${version}-linux-${arch}"
    curl -fsSL "https://nodejs.org/dist/v${version}/node-v${version}-linux-${arch}.tar.xz" -o /tmp/snck-node.tar.xz
    install -d -m 755 /opt/nodejs
    tar -xJf /tmp/snck-node.tar.xz -C /opt/nodejs
    ln -sfn "$root/bin/node" /usr/local/bin/node
    ln -sfn "$root/bin/npm" /usr/local/bin/npm
    ln -sfn "$root/bin/npx" /usr/local/bin/npx
    rm -f /tmp/snck-node.tar.xz
  fi
  command -v node >/dev/null || die "Node.js installation failed."
  ok "Installed Node.js $(node -v)."
}

ensure_user() {
  if ! id "$SERVICE_USER" >/dev/null 2>&1; then
    useradd --system --home-dir "$SERVICE_HOME" --create-home --shell /usr/sbin/nologin "$SERVICE_USER"
  fi
  install -d -m 750 -o "$SERVICE_USER" -g "$SERVICE_USER" "$SERVICE_HOME"
  install -d -m 750 -o "$SERVICE_USER" -g "$SERVICE_USER" "$SERVICE_HOME"/{servers,backups,uploads}
}

random_secret() { openssl rand -hex 32; }

write_env() {
  local env_file="$APP_DIR/.env"
  if [[ -f "$env_file" ]]; then
    ok "Keeping the existing $env_file (secrets are never regenerated)."
    return
  fi
  local public_url=""
  if [[ "${SNCK_NONINTERACTIVE:-0}" != "1" && "$TTY_OK" == "1" ]]; then
    printf '\n%sPanel port [%s]:%s ' "$B" "$PORT" "$R" >&2
    IFS= read -r -u 3 answer_port || true
    PORT="${answer_port:-$PORT}"
    printf '%sPublic URL (optional, e.g. https://panel.example.com):%s ' "$B" "$R" >&2
    IFS= read -r -u 3 public_url || true
    public_url="${public_url%/}"
  fi
  umask 077
  cat >"$env_file" <<EOF
# Generated by install.sh. Keep this file private.
NODE_ENV=production
HOST=0.0.0.0
PORT=${PORT}
SFTP_PORT=${SFTP_PORT}
JWT_SECRET=$(random_secret)
NODE_AUTH_SECRET=$(random_secret)
NODE_ENCRYPTION_KEY=$(random_secret)
PANEL_URL=${public_url}
PANEL_ALLOWED_ORIGINS=${public_url}
DOCKER_SOCKET_PATH=/var/run/docker.sock
NODE_HEARTBEAT_TIMEOUT_MS=45000
DEV_AUTO_LOGIN=false
EOF
  chown "$SERVICE_USER:$SERVICE_USER" "$env_file"
  chmod 600 "$env_file"
  ok "Created $env_file with fresh secrets."
}

fetch_source() {
  if [[ -d "$APP_DIR/.git" ]]; then
    info "Updating the existing checkout in $APP_DIR…"
    git -C "$APP_DIR" fetch --depth 1 origin "$BRANCH"
    git -C "$APP_DIR" reset --hard "origin/$BRANCH"
  elif [[ -e "$APP_DIR" && -n "$(ls -A "$APP_DIR" 2>/dev/null || true)" ]]; then
    die "$APP_DIR exists and is not a Git checkout. Move it away or set SNCK_PANEL_DIR."
  else
    info "Cloning $REPO_URL ($BRANCH)…"
    git clone --depth 1 --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
  fi
  ok "Source ready at $APP_DIR."
}

build_panel() {
  info "Installing dependencies (this can take a minute)…"
  ( cd "$APP_DIR" && npm ci --include=dev --no-audit --no-fund )
  info "Building the panel…"
  ( cd "$APP_DIR" && npm run build )
  install -d -m 750 -o "$SERVICE_USER" -g "$SERVICE_USER" "$APP_DIR/.data"
  chown -R "$SERVICE_USER:$SERVICE_USER" "$APP_DIR"
  chmod 600 "$APP_DIR/.env"
  ok "Build complete."
}

install_service() {
  has_systemd || { warn "systemd not available. Start manually with: sudo -u $SERVICE_USER bash -lc 'cd $APP_DIR && npm start'"; return; }
  local node_bin
  node_bin="$(command -v node)"
  cat >"/etc/systemd/system/${SERVICE}.service" <<EOF
[Unit]
Description=SNCK Panel (Node.js)
Documentation=https://github.com/SnckBoy/snck-panel.js
After=network-online.target docker.service
Wants=network-online.target

[Service]
Type=simple
User=${SERVICE_USER}
Group=${SERVICE_USER}
WorkingDirectory=${APP_DIR}
EnvironmentFile=${APP_DIR}/.env
ExecStart=${node_bin} ${APP_DIR}/dist/server.cjs
Restart=always
RestartSec=3
LimitNOFILE=65535
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ReadWritePaths=${APP_DIR} ${SERVICE_HOME}

[Install]
WantedBy=multi-user.target
EOF
  systemctl daemon-reload
  systemctl enable "$SERVICE" >/dev/null
  systemctl restart "$SERVICE"
  ok "systemd service ${SERVICE}.service started."
}

wait_for_health() {
  local url="http://127.0.0.1:${PORT}/health" i
  for i in $(seq 1 45); do
    if curl -fsS -m 2 "$url" >/dev/null 2>&1; then ok "Panel is healthy at $url"; return 0; fi
    sleep 1
  done
  warn "Health check did not pass within 45s. Recent logs:"
  journalctl -u "$SERVICE" -n 30 --no-pager 2>/dev/null || true
  return 1
}

open_firewall() {
  if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
    ufw allow "${PORT}/tcp" >/dev/null 2>&1 || true
    ufw allow "${SFTP_PORT}/tcp" >/dev/null 2>&1 || true
    ok "Opened ports ${PORT}/tcp and ${SFTP_PORT}/tcp in ufw."
  fi
}

public_ip() {
  curl -fsS -m 5 https://api.ipify.org 2>/dev/null || hostname -I 2>/dev/null | awk '{print $1}'
}

install_panel() {
  require_root
  check_os
  install_packages
  install_node
  ensure_user
  fetch_source
  write_env
  build_panel
  install_service
  open_firewall
  if wait_for_health; then
    local host
    host="$(public_ip)"
    printf '\n%sSNCK Panel installed.%s\n' "$B$GREEN" "$R"
    printf '  Open:  %shttp://%s:%s/setup%s\n' "$CYAN" "${host:-SERVER_IP}" "$PORT" "$R"
    printf '  First visit creates the Owner account.\n'
    printf '  Service: %ssystemctl status %s%s\n' "$DIM" "$SERVICE" "$R"
  fi
}

update_panel() {
  require_root
  [[ -d "$APP_DIR/.git" ]] || die "Panel is not installed at $APP_DIR."
  fetch_source
  build_panel
  has_systemd && systemctl restart "$SERVICE" || true
  wait_for_health || true
  ok "Update finished."
}

service_menu() {
  require_root
  while true; do
    clear 2>/dev/null || true
    printf '\n%sService control%s\n' "$B" "$R"
    printf '  [1] Status\n  [2] Start\n  [3] Stop\n  [4] Restart\n  [5] Live logs\n  [6] Back\n'
    local choice; choice="$(ask "Choose [1-6]: " "6")"
    case "$choice" in
      1) systemctl status "$SERVICE" --no-pager || true; pause ;;
      2) systemctl start "$SERVICE" && ok "Started."; pause ;;
      3) systemctl stop "$SERVICE" && ok "Stopped."; pause ;;
      4) systemctl restart "$SERVICE" && ok "Restarted."; pause ;;
      5) printf '%sCtrl+C to leave logs.%s\n' "$DIM" "$R"; journalctl -u "$SERVICE" -f || true ;;
      6) return ;;
      *) warn "Invalid choice." ;;
    esac
  done
}

create_user() {
  require_root
  [[ -d "$APP_DIR" ]] || die "Install the panel first."
  if [[ "$TTY_OK" != "1" ]]; then die "User creation needs an interactive terminal."; fi
  ( cd "$APP_DIR" && runuser -u "$SERVICE_USER" -- env HOME="$SERVICE_HOME" npm run createuser )
  has_systemd && systemctl restart "$SERVICE" || true
  ok "User saved. Restart complete."
}

install_docker() {
  require_root
  check_os
  if ! command -v docker >/dev/null 2>&1; then
    info "Installing Docker Engine…"
    apt-get update -y
    apt-get install -y docker.io docker-compose-v2 || apt-get install -y docker.io
  fi
  has_systemd && systemctl enable --now docker
  usermod -aG docker "$SERVICE_USER" 2>/dev/null || true
  docker info >/dev/null 2>&1 && ok "Docker is ready." || warn "Docker is installed but not reachable; check the daemon."
  printf 'Restart the panel service so it can access the Docker socket: systemctl restart %s\n' "$SERVICE"
}

diagnostics() {
  printf '\n%sDiagnostics%s\n' "$B" "$R"
  printf '  OS:      %s\n' "$(grep -E '^PRETTY_NAME=' /etc/os-release 2>/dev/null | cut -d= -f2- | tr -d '\"')"
  printf '  Node:    %s\n' "$(node -v 2>/dev/null || echo missing)"
  printf '  npm:     %s\n' "$(npm -v 2>/dev/null || echo missing)"
  printf '  Docker:  %s\n' "$(docker --version 2>/dev/null || echo 'not installed')"
  printf '  App dir: %s\n' "$APP_DIR"
  printf '  Port:    %s\n' "$PORT"
  if has_systemd; then
    printf '  Service: %s\n' "$(systemctl is-active "$SERVICE" 2>/dev/null || true)"
  fi
  printf '  Health:  '; curl -fsS -m 3 "http://127.0.0.1:${PORT}/health" 2>/dev/null || printf 'no response'
  printf '\n  Disk:    '; df -h "$APP_DIR" 2>/dev/null | awk 'NR==2 {print $4" free of "$2}' || true
}

uninstall_panel() {
  require_root
  local answer; answer="$(ask "Remove SNCK Panel? Type YES to confirm: " "")"
  [[ "$answer" == "YES" ]] || { info "Cancelled."; return; }
  if has_systemd; then
    systemctl disable --now "$SERVICE" >/dev/null 2>&1 || true
    rm -f "/etc/systemd/system/${SERVICE}.service"
    systemctl daemon-reload
  fi
  local keep; keep="$(ask "Keep panel data in $APP_DIR? [Y/n]: " "Y")"
  if [[ ! "$keep" =~ ^[Nn] ]]; then
    ok "Service removed. Files kept at $APP_DIR."
  else
    rm -rf "$APP_DIR"
    ok "Panel and its data removed."
  fi
}

usage() {
  cat <<'EOF'
SNCK Panel installer (Node.js edition)

Usage:
  curl -fsSL https://raw.githubusercontent.com/SnckBoy/snck-panel.js/main/install.sh | sudo bash
  sudo bash install.sh --install|--update|--status|--diagnostics|--uninstall
  sudo SNCK_NONINTERACTIVE=1 bash install.sh

Environment:
  SNCK_PANEL_DIR   install path (default /opt/snck-panel)
  SNCK_PORT        panel port (default 6767)
  SNCK_SFTP_PORT   SFTP port (default 6868)
  SNCK_REPO_URL    Git repository
  SNCK_BRANCH      branch (default main)

Requirements: Ubuntu 20.04+/Debian 11+ with root access. The installer sets up
Node.js 22, builds the panel, generates secrets in .env and registers a systemd
service. Minecraft servers require Docker (menu option 6, or the node installer
when using a separate VPS).
EOF
}

main() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --install) install_panel; exit 0 ;;
      --update) update_panel; exit 0 ;;
      --status) systemctl status "$SERVICE" --no-pager || true; exit 0 ;;
      --diagnostics) diagnostics; exit 0 ;;
      --uninstall) uninstall_panel; exit 0 ;;
      -h|--help) usage; exit 0 ;;
      *) die "Unknown argument: $1 (try --help)" ;;
    esac
  done

  if [[ "${SNCK_NONINTERACTIVE:-0}" == "1" || "$TTY_OK" != "1" ]]; then
    install_panel
    exit 0
  fi

  while true; do
    clear 2>/dev/null || true
    printf '\n%s╔══════════════════════════════════════════╗%s\n' "$B$CYAN" "$R"
    printf '%s║        SNCK PANEL  ·  NODE.JS           ║%s\n' "$B$CYAN" "$R"
    printf '%s╚══════════════════════════════════════════╝%s\n' "$B$CYAN" "$R"
    printf '  [1] Install panel\n'
    printf '  [2] Update panel\n'
    printf '  [3] Service control\n'
    printf '  [4] Create / reset a user\n'
    printf '  [5] Diagnostics\n'
    printf '  [6] Install Docker (local Minecraft servers)\n'
    printf '  [7] Uninstall\n'
    printf '  [8] Exit\n'
    local choice; choice="$(ask "Choose an option [1-8]: " "1")"
    case "$choice" in
      1) install_panel; pause ;;
      2) update_panel; pause ;;
      3) service_menu ;;
      4) create_user; pause ;;
      5) diagnostics; pause ;;
      6) install_docker; pause ;;
      7) uninstall_panel; pause ;;
      8) exit 0 ;;
      *) warn "Invalid choice." ;;
    esac
  done
}

main "$@"
