import { Request, Response } from "express";
import fs from "fs-extra";
import {
  activateWorld,
  archiveWorld,
  createWorld,
  deleteWorld,
  duplicateWorld,
  importWorldArchive,
  listWorlds,
  resolveWorldPath,
  streamWorldZip,
} from "../services/worlds.js";
import { audit } from "../services/security.js";

const localOnly = (req: Request, res: Response): boolean => {
  const server = (req as any).server;
  if (server?.nodeId && server.nodeId !== "local") {
    res.status(409).json({
      error: "World management currently runs on the panel's local node. This server is assigned to a remote node.",
      remoteNodeUnsupported: true,
    });
    return false;
  }
  return true;
};

const runningNotice = (req: Request): string | null => {
  const server = (req as any).server;
  return String(server?.status || "").toLowerCase() === "online"
    ? "Stop the server first. Minecraft holds world files open while it is running."
    : null;
};

export const getWorlds = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  try {
    const result = await listWorlds(req.params.id);
    res.json(result);
  } catch (error: any) {
    res.status(500).json({ error: error?.message || "Unable to read worlds." });
  }
};

export const createWorldHandler = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  try {
    const result = await createWorld(req.params.id, req.body || {});
    await audit("world.created", req, { serverId: req.params.id, world: result.name });
    res.json({
      ...result,
      message: `“${result.name}” will be generated by the server on its next start. Restart the server to apply it.`,
    });
  } catch (error: any) {
    res.status(400).json({ error: error?.message || "Unable to create the world." });
  }
};

export const activateWorldHandler = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  try {
    const result = await activateWorld(req.params.id, req.params.name);
    await audit("world.activated", req, { serverId: req.params.id, world: result.activeWorld });
    res.json({ ...result, message: `“${result.activeWorld}” is now the active world. Restart the server to load it.` });
  } catch (error: any) {
    res.status(400).json({ error: error?.message || "Unable to activate the world." });
  }
};

export const deleteWorldHandler = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  const running = runningNotice(req);
  if (running) return res.status(409).json({ error: running });
  try {
    await deleteWorld(req.params.id, req.params.name);
    await audit("world.deleted", req, { serverId: req.params.id, world: req.params.name });
    res.json({ success: true });
  } catch (error: any) {
    res.status(400).json({ error: error?.message || "Unable to delete the world." });
  }
};

export const duplicateWorldHandler = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  const running = runningNotice(req);
  if (running) return res.status(409).json({ error: running });
  try {
    const result = await duplicateWorld(req.params.id, req.params.name, req.body?.targetName);
    await audit("world.duplicated", req, { serverId: req.params.id, world: req.params.name, target: result.name });
    res.json(result);
  } catch (error: any) {
    res.status(400).json({ error: error?.message || "Unable to duplicate the world." });
  }
};

export const downloadWorldHandler = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  try {
    const { archive, filename } = await streamWorldZip(req.params.id, req.params.name);
    res.setHeader("Content-Type", "application/zip");
    res.setHeader("Content-Disposition", `attachment; filename="${encodeURIComponent(filename)}"`);
    archive.on("error", (error: Error) => {
      console.error("World archive error:", error);
      if (!res.headersSent) res.status(500).end();
      else res.end();
    });
    archive.pipe(res);
    void archive.finalize();
  } catch (error: any) {
    if (!res.headersSent) res.status(400).json({ error: error?.message || "Unable to archive the world." });
  }
};

export const backupWorldHandler = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  const running = runningNotice(req);
  if (running) return res.status(409).json({ error: running });
  try {
    const result = await archiveWorld(req.params.id, req.params.name);
    await audit("world.archived", req, { serverId: req.params.id, world: req.params.name, filename: result.filename });
    res.json({ ...result, message: "World archived into the server's managed backups." });
  } catch (error: any) {
    res.status(400).json({ error: error?.message || "Unable to archive the world." });
  }
};

export const importWorldHandler = async (req: Request, res: Response) => {
  if (!localOnly(req, res)) return;
  const running = runningNotice(req);
  if (running) return res.status(409).json({ error: running });
  const file = (req as any).file as { path?: string } | undefined;
  if (!file?.path) return res.status(400).json({ error: "Attach a .zip world archive." });
  try {
    const result = await importWorldArchive(req.params.id, file.path, req.body?.name);
    await audit("world.imported", req, { serverId: req.params.id, world: result.name });
    res.json({ ...result, message: "World imported. Activate it and restart the server when ready." });
  } catch (error: any) {
    res.status(400).json({ error: error?.message || "World import failed." });
  } finally {
    await fs.remove(file.path).catch(() => undefined);
  }
};

/** Expose a resolved path for tests and diagnostics only; never used to serve downloads. */
export const getWorldPath = (serverId: string, name: string) => resolveWorldPath(serverId, name);
